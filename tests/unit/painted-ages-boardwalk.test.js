function emptyArrays() {
    return {
        positions: [], colours: [], detailData: [], horizonData: [],
    };
}

/** Independent index traversal: this does not use the helper's fan row/column lookup. */
function renderedSurface(bake, route) {
    const minX = Math.min(...route.map((point) => point.x)) - 8;
    const maxX = Math.max(...route.map((point) => point.x)) + 8;
    const minZ = Math.min(...route.map((point) => point.z)) - 8;
    const maxZ = Math.max(...route.map((point) => point.z)) + 8;
    const triangles = [];
    for (let i = 0; i < bake.indices.length; i += 3) {
        const vertices = [0, 1, 2].map((corner) => {
            const offset = bake.indices[i + corner] * 3;
            return new THREE.Vector3().fromArray(bake.positions, offset);
        });
        const lowX = Math.min(...vertices.map((v) => v.x));
        const highX = Math.max(...vertices.map((v) => v.x));
        const lowZ = Math.min(...vertices.map((v) => v.z));
        const highZ = Math.max(...vertices.map((v) => v.z));
        if (highX < minX || lowX > maxX || highZ < minZ || lowZ > maxZ) continue;
        triangles.push({
            vertices: vertices.map((v) => new THREE.Vector3(v.x, 0, v.z)),
            heights: vertices.map((v) => v.y),
            lowX,
            highX,
            lowZ,
            highZ,
        });
    }
    const query = new THREE.Vector3();
    const weights = new THREE.Vector3();
    return (x, z) => {
        query.set(x, 0, z);
        for (const triangle of triangles) {
            if (x < triangle.lowX || x > triangle.highX || z < triangle.lowZ || z > triangle.highZ) continue;
            THREE.Triangle.getBarycoord(query, ...triangle.vertices, weights);
            if (Math.min(weights.x, weights.y, weights.z) < -1e-6) continue;
            return weights.x * triangle.heights[0] + weights.y * triangle.heights[1] + weights.z * triangle.heights[2];
        }
        return NaN;
    };
}

const vertexKey = (x, y, z) => [x, y, z].map((value) => Math.fround(value).toFixed(4)).join(',');
const insidePolygon = (polygon, x, z) => {
    let sign = 0;
    for (let i = 0; i < polygon.length; i++) {
        const a = polygon[i]; const b = polygon[(i + 1) % polygon.length];
        const cross = (b.x - a.x) * (z - a.z) - (b.z - a.z) * (x - a.x);
        if (Math.abs(cross) < 1e-7) continue;
        if (sign && sign * cross < 0) return false;
        sign = Math.sign(cross);
    }
    return true;
};

describe('Painted Ages constructed route', () => {
    it.each(['Minimal', 'High'])('keeps %s flights walkable and supported by the actual rendered ground', (quality) => {
        const tier = tierFor(quality);
        const bake = bakeTerrain({ vertices: tier.terrainVertices, seed: 0x5ed1 });
        const arrays = emptyArrays();
        const plan = appendBoardwalk(arrays, { bake, tier });
        expect(plan.found).toBe(true);
        expect(plan.flights.length).toBeGreaterThan(5);
        expect(plan.landings.length).toBe(plan.flights.length + 1);
        const vertices = arrays.positions.length / 3;
        expect(plan.verticesAdded).toBe(vertices);
        expect(vertices).toBeLessThan(100000);
        expect(arrays.colours.length).toBe(arrays.positions.length);
        expect(arrays.detailData.length).toBe(vertices * 4);
        expect(arrays.horizonData.length).toBe(vertices);
        for (const values of Object.values(arrays)) expect(values.every(Number.isFinite)).toBe(true);
        // Includes normals generated by createLand: five attributes, no extra mesh or event pool.
        expect(vertices * (3 + 3 + 3 + 4 + 1) * 4).toBeLessThan(5600000);

        let cursor = 0;
        for (const flight of plan.flights) {
            expect(flight.run).toBeGreaterThanOrEqual(0.29 - 1e-8);
            expect(Math.abs(flight.rise)).toBeLessThanOrEqual(0.19 + 1e-8);
            const steps = plan.treads.slice(cursor, cursor + flight.steps);
            expect(steps).toHaveLength(flight.steps);
            expect(Math.abs(steps[0].top - flight.from.y)).toBeLessThanOrEqual(0.19 + 1e-8);
            expect(Math.abs(steps.at(-1).top - flight.to.y)).toBeLessThanOrEqual(0.19 + 1e-8);
            for (let i = 1; i < steps.length; i++) {
                expect(steps[i].top - steps[i - 1].top).toBeCloseTo(flight.rise, 7);
                expect(Math.hypot(steps[i].x - steps[i - 1].x, steps[i].z - steps[i - 1].z))
                    .toBeCloseTo(flight.run, 7);
            }
            cursor += flight.steps;
        }
        expect(cursor).toBe(plan.treads.length);

        const ground = renderedSurface(bake, plan.route);
        const emitted = new Set();
        for (let i = 0; i < arrays.positions.length; i += 3) {
            emitted.add(vertexKey(...arrays.positions.slice(i, i + 3)));
        }
        let minimumClearance = Infinity;
        let missingCorners = 0;
        for (const tread of plan.treads) {
            for (const across of [-1, 1]) {
                for (const along of [-1, 1]) {
                    const acrossDistance = across * tread.width * 0.5;
                    const alongDistance = along * tread.depth * 0.5;
                    const x = tread.x + tread.tz * acrossDistance + tread.tx * alongDistance;
                    const z = tread.z - tread.tx * acrossDistance + tread.tz * alongDistance;
                    if (!emitted.has(vertexKey(x, tread.top, z))) missingCorners += 1;
                    minimumClearance = Math.min(minimumClearance, tread.top - tread.thickness - ground(x, z));
                }
            }
        }
        expect(missingCorners, 'reported tread corners must belong to the actual emitted mesh').toBe(0);
        expect(minimumClearance, 'every tread underside clears the rendered terrain').toBeGreaterThan(0.1);
        let minimumLandingClearance = Infinity;
        for (let i = 0; i < plan.landings.length; i++) {
            const landing = plan.landings[i];
            expect(landing.polygon.length).toBeGreaterThanOrEqual(3);
            for (const { x, z } of landing.polygon) {
                expect(emitted.has(vertexKey(x, landing.top, z)), 'landing corners exist in the mesh').toBe(true);
                minimumLandingClearance = Math.min(minimumLandingClearance, landing.top - 0.1 - ground(x, z));
            }
            const lowX = Math.min(...landing.polygon.map((p) => p.x));
            const highX = Math.max(...landing.polygon.map((p) => p.x));
            const lowZ = Math.min(...landing.polygon.map((p) => p.z));
            const highZ = Math.max(...landing.polygon.map((p) => p.z));
            for (let x = lowX; x <= highX; x += 0.35) {
                for (let z = lowZ; z <= highZ; z += 0.35) {
                    if (!insidePolygon(landing.polygon, x, z)) continue;
                    minimumLandingClearance = Math.min(minimumLandingClearance, landing.top - 0.1 - ground(x, z));
                }
            }
            if (i < plan.flights.length) {
                const flight = plan.flights[i];
                for (const [mouth, endpoint, top] of [
                    [landing.exit, flight.from, landing.top],
                    [plan.landings[i + 1].entrance, flight.to, plan.landings[i + 1].top],
                ]) {
                    expect((mouth[0].x + mouth[1].x) / 2).toBeCloseTo(endpoint.x, 7);
                    expect((mouth[0].z + mouth[1].z) / 2).toBeCloseTo(endpoint.z, 7);
                    expect(top).toBeCloseTo(endpoint.y, 7);
                }
            }
        }
        expect(minimumLandingClearance, 'turn platforms clear terrain between their corners').toBeGreaterThan(0.1);
        expect(plan.landings.at(-1).terminal, 'the route ends on a level overlook').toBe(true);
        const tops = new Map();
        for (const tread of plan.treads) {
            const height = Math.fround(tread.top).toFixed(4);
            if (!tops.has(height)) tops.set(height, []);
            tops.get(height).push(tread);
        }
        let minimumArea = Infinity;
        let invertedTops = 0;
        const coveredTreads = new Set();
        const positions = new Float32Array(arrays.positions);
        for (let i = 0; i < positions.length; i += 9) {
            const ax = positions[i]; const ay = positions[i + 1]; const az = positions[i + 2];
            const ux = positions[i + 3] - ax; const uy = positions[i + 4] - ay; const uz = positions[i + 5] - az;
            const vx = positions[i + 6] - ax; const vy = positions[i + 7] - ay; const vz = positions[i + 8] - az;
            const ny = uz * vx - ux * vz;
            minimumArea = Math.min(minimumArea, Math.hypot(uy * vz - uz * vy, ny, ux * vy - uy * vx));
            if (Math.abs(uy) > 1e-5 || Math.abs(vy) > 1e-5) continue;
            for (const tread of tops.get(ay.toFixed(4)) || []) {
                const x = ax + (ux + vx) / 3 - tread.x;
                const z = az + (uz + vz) / 3 - tread.z;
                if (Math.abs(x * tread.tx + z * tread.tz) > tread.depth / 2 + 1e-5
                    || Math.abs(x * tread.tz - z * tread.tx) > tread.width / 2 + 1e-5) continue;
                coveredTreads.add(tread);
                if (ny <= 0) invertedTops += 1;
            }
        }
        expect(minimumArea, 'no zero-area faces after GPU float conversion').toBeGreaterThan(1e-8);
        expect(coveredTreads.size).toBe(plan.treads.length);
        expect(invertedTops, 'emitted tread surfaces face upward').toBe(0);
        let minimumEmbed = Infinity;
        let maximumEmbed = -Infinity;
        for (const { foot, top } of plan.supports) {
            const embed = ground(foot.x, foot.z) - foot.y;
            minimumEmbed = Math.min(minimumEmbed, embed);
            maximumEmbed = Math.max(maximumEmbed, embed);
            expect(top.y).toBeGreaterThan(foot.y);
            expect(top.y - foot.y).toBeLessThan(8);
        }
        expect(minimumEmbed, 'support feet intersect the rendered ground').toBeGreaterThan(0.05);
        expect(maximumEmbed, 'supports use the rendered surface, not the finer analytical height').toBeLessThan(0.3);
    }, 20000);

    it('supports deterministic analytic fallback bakes and synthetic shader fixtures', () => {
        const bake = { heightAt: (x, z) => x * 0.1 - z * 0.15 };
        expect(createBoardwalkSurface(bake)).toBe(bake.heightAt);
        const first = emptyArrays();
        const second = emptyArrays();
        const tier = tierFor('Minimal');
        const a = appendBoardwalk(first, { bake, tier });
        const b = appendBoardwalk(second, { bake, tier });
        expect(a.found).toBe(true);
        expect(a).toEqual(b);
        expect(first).toEqual(second);
    });
});

function renderer() {
    return {
        contextNode: context(),
        lighting: { enabled: false },
        backend: {
            device: null,
            capabilities: { getUniformBufferLimit: () => 65536 },
            extensions: { has: () => false },
            utils: { getTextureSampleData: () => ({ samples: 1, primarySamples: 1, isMSAA: false }) },
            compatibilityMode: false,
        },
        getRenderTarget: () => null,
        getMRT: () => null,
        shadowMap: { enabled: false, type: 0 },
        capabilities: {},
        library: { fromMaterial: (material) => material },
        nodes: {},
        getOutputRenderTarget: () => null,
        getOutputBufferType: () => THREE.HalfFloatType,
        currentColorSpace: 'srgb',
        outputColorSpace: 'srgb',
        toneMapping: 0,
        xr: { enabled: false },
        debug: { checkShaderErrors: false, diagnostics: { keywords: true } },
        getUniformBufferLimit: () => 65536,
        hasFeature: () => false,
        isOutputTarget: false,
        logarithmicDepthBuffer: false,
        reverseDepth: false,
        highPrecision: false,
    };
}

describe('Painted Ages timber field', () => {
    it('keeps grain repeatable and filterable through a bounded complete mip chain', () => {
        const first = createTimberField();
        const second = createTimberField();
        try {
            expect(first.image.data).toEqual(second.image.data);
            expect(first.image.data).not.toBe(second.image.data);
            expect(first.image.width).toBe(128);
            expect(first.image.height).toBe(128);
            expect(first.type).toBe(THREE.UnsignedByteType);
            expect(first.colorSpace).toBe(THREE.NoColorSpace);
            expect(first.wrapS).toBe(THREE.RepeatWrapping);
            expect(first.wrapT).toBe(THREE.RepeatWrapping);
            expect(first.minFilter).toBe(THREE.LinearMipmapLinearFilter);
            expect(first.generateMipmaps).toBe(false);
            expect(first.mipmaps).toHaveLength(8);
            expect(first.mipmaps.reduce((bytes, mip) => bytes + mip.data.byteLength, 0)).toBe(87380);
            expect(first.image.data).toBe(first.mipmaps[0].data);
            for (const [level, mip] of first.mipmaps.entries()) {
                const width = 128 >> level;
                expect([mip.width, mip.height, mip.data.length]).toEqual([width, width, width * width * 4]);
            }
            const grain = first.image.data.filter((value, index) => index % 4 === 0);
            expect(new Set(grain).size).toBeGreaterThan(32);
            const mean = grain.reduce((sum, value) => sum + value, 0) / grain.length;
            expect(Math.abs(first.mipmaps.at(-1).data[0] - mean)).toBeLessThan(4);
        } finally {
            first.dispose();
            second.dispose();
        }
    });
});

describe.each(['Minimal', 'Low', 'High'])('Painted Ages detail material at %s', (quality) => {
    it.each([['WGSL', THREE.WGSLNodeBuilder], ['GLSL', THREE.GLSLNodeBuilder]])(
        'builds %s within budget and disposes its owned texture',
        (label, Builder) => {
            const geometry = new THREE.BoxGeometry(1, 1, 1);
            const { count } = geometry.getAttribute('position');
            geometry.setAttribute('color', new THREE.Float32BufferAttribute(new Float32Array(count * 3).fill(0.4), 3));
            geometry.setAttribute('paDetail', new THREE.Float32BufferAttribute(new Float32Array(count * 4).fill(1), 4));
            geometry.setAttribute('paDetailHorizon', new THREE.Float32BufferAttribute(new Float32Array(count), 1));
            const shading = createDetailMaterial(createPaintedAgesUniforms(), tierFor(quality));
            const mesh = new THREE.Mesh(geometry, shading.material);
            const disposed = { material: 0, texture: 0 };
            shading.material.addEventListener('dispose', () => { disposed.material += 1; });
            const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
            const error = vi.spyOn(console, 'error').mockImplementation(() => {});
            try {
                const builder = new Builder(mesh, renderer());
                builder.scene = new THREE.Scene();
                builder.camera = new THREE.PerspectiveCamera();
                builder.material = shading.material;
                builder.context.material = shading.material;
                builder.build();
                expect(warn.mock.calls).toEqual([]);
                expect(error.mock.calls).toEqual([]);
                expect(builder.fragmentShader.length).toBeLessThan(96 * 1024);
                expect(builder.fragmentShader).not.toMatch(/\bNaN\b|\bInfinity\b/);
                const textures = builder.uniforms.fragment.filter((entry) => entry.type === 'texture');
                expect(textures).toHaveLength(quality === 'Minimal' ? 0 : 1);
                for (const { node } of textures) {
                    expect(node.value.name).toBe('PaintedAgesTimberGrain');
                    expect(node.value.mipmaps.reduce((bytes, mip) => bytes + mip.data.byteLength, 0)).toBe(87380);
                    node.value.addEventListener('dispose', () => { disposed.texture += 1; });
                }
            } finally {
                shading.dispose();
                geometry.dispose();
                warn.mockRestore();
                error.mockRestore();
            }
            expect(disposed).toEqual({ material: 1, texture: quality === 'Minimal' ? 0 : 1 });
        },
    );
});
