describe('Summer swans in the world', () => {
    const assetDirectory = new URL('../../src/themes/summer/assets/', import.meta.url);
    const SLOW = 120000;
    let bundle = null;

    async function parseGlb(file) {
        const bytes = readFileSync(new URL(file, assetDirectory));
        const buffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
        return new GLTFLoader().parseAsync(buffer, '');
    }

    /** The real asset pack, parsed from disk; the sprite sheet is a stand-in data texture. */
    async function loadBundle() {
        const names = Object.keys(SUMMER_TREE_URLS);
        const [foliage, props, ...trees] = await Promise.all([parseGlb('summer-foliage.glb'),
            parseGlb('summer-props.glb'), ...names.map((name) => parseGlb(`${name}.glb`))]);
        const assets = {
            foliage: parseSummerMeshes(foliage, 'Foliage'),
            props: parseSummerMeshes(props, 'Props'),
            trees: {},
            impostors: {
                ...summerImpostorLayout(),
                texture: new THREE.DataTexture(new Uint8Array(64).fill(255), 4, 4),
            },
        };
        names.forEach((name, index) => { assets.trees[name] = parseSummerTree(trees[index], name); });
        return assets;
    }

    afterAll(() => {
        if (bundle) disposeSummerAssets(bundle);
    });

    it('builds them with the world, mirrors them in the lake, rings its water and lets go of them', async () => {
        bundle = await loadBundle();
        const scene = new THREE.Scene();
        const camera = new THREE.PerspectiveCamera(50, 16 / 9, 0.3, 3400);
        const world = new SummerWorld({
            scene, camera, quality: 'Minimal', rng: seededRandom(624), assets: bundle,
        });
        expect(world.getDiagnostics().swans).toBeNull();
        world.setMotion(0.25);
        world.build();
        const { swans } = world;
        expect(swans).toBeInstanceOf(SummerSwans);
        expect(swans.group.parent).toBe(world.group);
        expect(swans.light).toBe(world.light);
        expect(swans.tier).toBe(SUMMER_TIERS.Minimal);
        // Reduce motion set before the build reaches them, and every change after it.
        expect(swans.motion).toBe(0.25);
        world.setMotion(1);
        expect(swans.motion).toBe(1);
        expect(world.getDiagnostics().swans).toEqual({ afloat: 2, cygnets: 2, flying: 0 });
        // In the lake's mirror, and still drawn by the main camera.
        const drawn = [];
        swans.group.traverse((object) => drawn.push(object));
        expect(drawn).toHaveLength(4);
        for (const object of drawn) {
            expect(object.layers.isEnabled(SUMMER_MIRROR_LAYER), object.name).toBe(true);
            expect(object.layers.isEnabled(0), object.name).toBe(true);
        }
        // The world drives them and hands their rings to the lake.
        const added = vi.spyOn(world.lake.ripples, 'add');
        const updated = vi.spyOn(swans, 'update');
        for (let frame = 0; frame < 15 * 60; frame += 1) world.update(frame * STEP, STEP, { emitters: [] });
        expect(updated).toHaveBeenCalledTimes(15 * 60);
        expect(updated.mock.calls[7].slice(0, 2)).toEqual([7 * STEP, STEP]);
        expect(updated.mock.calls[7][3]).toBe(world.worn);
        const { round } = swans;
        const wakes = added.mock.calls.filter(([x, z]) => Math.hypot(x - round.x, z - round.z) < round.a + 2);
        expect(wakes.length).toBeGreaterThanOrEqual(2);
        for (const [, , strength] of wakes) expect(strength).toBeLessThanOrEqual(0.18);
        // A level's flight (the lead wires the call), seen in the diagnostics; a reset forgets it.
        expect(swans.takeWing()).toBe(true);
        world.update(15, STEP, { emitters: [] });
        expect(world.getDiagnostics().swans).toEqual({ afloat: 2, cygnets: 2, flying: 3 });
        world.resetEffects();
        expect(swans.flight.live).toBe(false);
        expect(world.getDiagnostics().swans.flying).toBe(0);
        const disposed = vi.spyOn(swans, 'dispose');
        world.dispose();
        expect(disposed).toHaveBeenCalledOnce();
        expect(world.swans).toBeNull();
        expect(world.getDiagnostics().swans).toBeNull();
        expect(scene.children).toHaveLength(0);
    }, SLOW);
});
