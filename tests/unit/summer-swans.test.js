    it('calms the birds under Reduce motion, and rocks them a little more in a gust', () => {
        const { swans } = createSwans('High');
        swans.build();
        const afloat = swans.group.children[0].geometry.getAttribute('iSwanA').data.array;
        const lean = () => Math.acos(Math.min(1, birdOf(afloat, 0).up[1]));
        let rocked = 0;
        let gusted = 0;
        let still = 0;
        let dipped = 0;
        for (let time = 0; time < 120; time += 0.25) {
            swans.setMotion(1);
            swans.update(time, 0.25, {}, { motion: 1, gust: 0 });
            rocked = Math.max(rocked, lean());
            swans.update(time, 0.25, {}, { motion: 1, gust: 1 });
            gusted = Math.max(gusted, lean());
            swans.setMotion(0);
            swans.update(time, 0.25, {}, { motion: 1, gust: 1 });
            still = Math.max(still, lean());
            dipped = Math.max(dipped, birdOf(afloat, 0).second, birdOf(afloat, 1).second);
            // Still in the water, still swimming the round: only the manner is calmer (the cob's
            // wings stay as he always carries them, a little raised).
            expect(birdOf(afloat, 0).first).toBeCloseTo(0.18, 6);
        }
        expect(rocked).toBeGreaterThan(0.015);
        expect(rocked).toBeLessThan(0.06);
        expect(gusted).toBeGreaterThan(rocked * 1.8);
        expect(gusted).toBeLessThan(0.15);
        expect(still).toBe(0);
        expect(dipped).toBe(0);
        for (const junk of [NaN, undefined, 'fast']) {
            swans.setMotion(junk);
            expect(swans.motion).toBe(1);
        }
        swans.setMotion(7);
        expect(swans.motion).toBe(1);
        swans.setMotion(-1);
        expect(swans.motion).toBe(0);
    });

