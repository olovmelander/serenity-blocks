/**
 * Painted Ages' bearded vulture — the model the Blender script writes
 * (scripts/blender/painted_ages_vulture.py → painted-ages-vulture-model.js): its numbers, its
 * size and budget, the silhouette that makes it a lammergeier (long narrow wings to a point, a
 * long wedge of a tail, a small head), its plumage, the shares the vertex stage folds it by, and
 * the theme's own twin of that vertex stage held to the script's (`checks`).
 */
import { readFileSync, readdirSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import * as THREE from 'three/webgpu';
import { PAINTED_AGES_VULTURE } from '../../src/themes/painted-ages/painted-ages-vulture-model.js';
import { VULTURE_FLIGHT, VULTURE_SPAN } from '../../src/themes/painted-ages/painted-ages-vulture-routes.js';
import { poseVulture, vultureModel } from '../../src/themes/painted-ages/painted-ages-vultures.js';

const M = PAINTED_AGES_VULTURE;
const source = (path) => readFileSync(new URL(`../../${path}`, import.meta.url), 'utf8');
const finite = (array) => Array.prototype.every.call(array, Number.isFinite);
const model = vultureModel();
const indices = Array.from({ length: model.vertexCount }, (_, i) => i);
const vertex = (i) => [model.positions[i * 3], model.positions[i * 3 + 1], model.positions[i * 3 + 2]];
const normal = (i) => [model.normals[i * 3], model.normals[i * 3 + 1], model.normals[i * 3 + 2]];
const rig = (i) => [model.rig[i * 4], model.rig[i * 4 + 1], model.rig[i * 4 + 2], model.rig[i * 4 + 3]];
const colour = (i) => [model.colours[i * 4], model.colours[i * 4 + 1], model.colours[i * 4 + 2]];
const luma = (i) => 0.2126 * colour(i)[0] + 0.7152 * colour(i)[1] + 0.0722 * colour(i)[2];
const part = (name) => indices.filter((i) => model.parts[i] === M.parts.indexOf(name));
const WING = M.parts.indexOf('wing');
const TAIL = M.parts.indexOf('tail');

describe('Painted Ages vulture model', () => {
    it('is written by the Blender script, as a module and not as an asset', () => {
        const text = source('src/themes/painted-ages/painted-ages-vulture-model.js');
        expect(text).toMatch(/GENERATED by scripts\/blender\/painted_ages_vulture\.py/);
        expect(text).toMatch(/blender --background --factory-startup --python scripts\/blender\/painted_ages_vulture\.py/);
        expect(text).toMatch(/--out src\/themes\/painted-ages/);
        expect(source('scripts/blender/painted_ages_vulture.py')).toMatch(/painted-ages-vulture-model\.js/);
        // No file to load: the theme's asset folder is the baked land's alone.
        const assets = readdirSync(new URL('../../src/themes/painted-ages/assets/', import.meta.url));
        expect(assets.filter((name) => /vulture|\.glb$/i.test(name))).toEqual([]);
        // The bird is this theme's own: nothing of another theme's is imported.
        for (const file of ['painted-ages-vultures.js', 'painted-ages-vulture-routes.js']) {
            const imports = [...source(`src/themes/painted-ages/${file}`).matchAll(/from '([^']+)'/g)].map((m) => m[1]);
            expect(imports.filter((from) => /themes\/(?!painted-ages|shared)/.test(from) || /^\.\.\/(?!shared\/)/.test(from))).toEqual([]);
        }
        expect(source('src/themes/painted-ages/painted-ages-vulture-routes.js')).not.toMatch(/from 'three/);
    });

    it('is a finite, indexed mesh of a few hundred triangles at a bearded vulture\'s real size', () => {
        expect(model.vertexCount).toBe(M.vertexCount);
        expect(model.triangleCount).toBe(M.triangleCount);
        expect(model.triangleCount).toBeGreaterThanOrEqual(250);
        expect(model.triangleCount).toBeLessThanOrEqual(500);
        expect(model.positions).toHaveLength(model.vertexCount * 3);
        expect(model.normals).toHaveLength(model.vertexCount * 3);
        expect(model.colours).toHaveLength(model.vertexCount * 4);
        expect(model.rig).toHaveLength(model.vertexCount * 4);
        expect(model.feather).toHaveLength(model.vertexCount * 4);
        expect(model.parts).toHaveLength(model.vertexCount);
        expect(model.index).toHaveLength(model.triangleCount * 3);
        for (const array of [model.positions, model.normals, model.colours, model.rig, model.feather]) {
            expect(finite(array)).toBe(true);
        }
        expect(Math.max(...model.index)).toBeLessThan(model.vertexCount);
        expect(Math.min(...model.index)).toBe(0);
        // Every vertex is used, and no triangle is a sliver of nothing.
        expect(new Set(model.index).size).toBe(model.vertexCount);
        for (let t = 0; t < model.triangleCount; t += 1) {
            const [a, b, c] = [0, 1, 2].map((k) => new THREE.Vector3(...vertex(model.index[t * 3 + k])));
            expect(b.sub(a).cross(c.sub(a)).length(), `triangle ${t}`).toBeGreaterThan(1e-7);
        }
        // Real size: about 2.7 m from wingtip to wingtip, mirrored, the head ahead and the tail behind.
        const xs = indices.map((i) => vertex(i)[0]);
        const zs = indices.map((i) => vertex(i)[2]);
        expect(Math.max(...xs) - Math.min(...xs)).toBeCloseTo(VULTURE_SPAN, 2);
        expect(M.span).toBeCloseTo(VULTURE_SPAN, 3);
        expect(VULTURE_SPAN).toBeGreaterThan(2.5);
        expect(VULTURE_SPAN).toBeLessThan(2.9);
        expect(Math.max(...xs)).toBeCloseTo(-Math.min(...xs), 3);
        expect(M.length).toBeCloseTo(Math.max(...zs) - Math.min(...zs), 3);
        expect(M.length).toBeGreaterThan(1.1);
        expect(M.length).toBeLessThan(1.45);
        // Unit normals, and the parts the script names.
        for (const i of indices) {
            expect(Math.hypot(...normal(i))).toBeCloseTo(1, 1);
            expect(model.parts[i]).toBeLessThan(M.parts.length);
        }
        expect(M.parts).toEqual(['body', 'head', 'bill', 'wing', 'tail']);
    });

    it('faces outward: the winding the script lists is the winding the eye meets', () => {
        // (A Blender export that turned the triangles would be drawn inside out, lit from behind.)
        let agree = 0;
        let up = 0;
        let flat = 0;
        for (let t = 0; t < model.triangleCount; t += 1) {
            const tri = [0, 1, 2].map((k) => model.index[t * 3 + k]);
            const [a, b, c] = tri.map((i) => new THREE.Vector3(...vertex(i)));
            const face = b.clone().sub(a).cross(c.clone().sub(a)).normalize();
            const mean = tri.reduce((sum, i) => sum.add(new THREE.Vector3(...normal(i))), new THREE.Vector3()).normalize();
            if (face.dot(mean) > 0) agree += 1;
            // A wing's upper faces look up and its lower ones down: the mean of what looks up lies higher.
            if (tri.every((i) => model.parts[i] === WING) && Math.abs(face.y) > 0.8) {
                flat += 1;
                const y = (a.y + b.y + c.y) / 3;
                if (Math.sign(face.y) === Math.sign(y - M.wrist[1]) || Math.abs(y - M.wrist[1]) < 0.012) up += 1;
            }
        }
        expect(agree / model.triangleCount).toBeGreaterThan(0.97);
        expect(flat).toBeGreaterThan(100);
        expect(up / flat).toBeGreaterThan(0.9);
    });

    it('has the lammergeier\'s silhouette: long narrow wings to a point, a long wedge of a tail, a small head', () => {
        const wing = part('wing');
        const tail = part('tail');
        const head = [...part('head'), ...part('bill')];
        const body = part('body');
        // Narrow: the wing's chord (leading to trailing edge at one station of the span) is under
        // a sixth of the span anywhere along the arm.
        const chordAt = (x) => {
            const zs = wing.filter((i) => Math.abs(vertex(i)[0] - x) < 0.012).map((i) => vertex(i)[2]);
            expect(zs.length, `station ${x}`).toBeGreaterThanOrEqual(5);
            return Math.max(...zs) - Math.min(...zs);
        };
        for (const x of [0.16, 0.27, 0.41, 0.52]) {
            expect(chordAt(x)).toBeLessThan(VULTURE_SPAN / 6);
            expect(chordAt(x)).toBeGreaterThan(0.3);
        }
        // To a point: the hand tapers, and the wing ends in parted fingers (flat feathers of
        // their own beyond the hand, the middle one the longest).
        expect(chordAt(0.98)).toBeLessThan(chordAt(0.41) * 0.6);
        const tipX = Math.max(...wing.map((i) => vertex(i)[0]));
        const tips = wing.filter((i) => vertex(i)[0] > 1.1 && rig(i)[1] > 0.99);
        expect(tips.length).toBeGreaterThanOrEqual(10);
        const tipZ = wing.filter((i) => vertex(i)[0] > tipX - 0.02).map((i) => vertex(i)[2]);
        expect(Math.max(...tipZ)).toBeLessThan(0.05); // swept back behind the wrist
        // The tail: long (over a third of the bird), widest past its middle, and in to a point.
        const tz = tail.map((i) => vertex(i)[2]);
        const tailLength = Math.max(...tz) - Math.min(...tz);
        expect(tailLength).toBeGreaterThan(0.45);
        expect(tailLength / M.length).toBeGreaterThan(0.36);
        const widest = tail.reduce((best, i) => (Math.abs(vertex(i)[0]) > Math.abs(vertex(best)[0]) ? i : best), tail[0]);
        const along = (Math.max(...tz) - vertex(widest)[2]) / tailLength;
        expect(along).toBeGreaterThan(0.45);
        expect(along).toBeLessThan(0.75);
        expect(Math.abs(vertex(widest)[0]) * 2).toBeGreaterThan(0.4);
        const point = tail.filter((i) => vertex(i)[2] < Math.min(...tz) + 0.01);
        point.forEach((i) => expect(Math.abs(vertex(i)[0])).toBeLessThan(0.01));
        // The tail is wider than the body and reaches well behind the wing.
        const bodyWidth = 2 * Math.max(...body.map((i) => Math.abs(vertex(i)[0])));
        expect(Math.abs(vertex(widest)[0]) * 2).toBeGreaterThan(bodyWidth * 1.5);
        expect(Math.min(...tz)).toBeLessThan(Math.min(...wing.map((i) => vertex(i)[2])) - 0.3);
        // A small head on a short neck: it stands ahead of the wing, no wider than half the body.
        const headWidth = 2 * Math.max(...head.map((i) => Math.abs(vertex(i)[0])));
        expect(headWidth).toBeLessThan(bodyWidth * 0.5);
        const ahead = Math.max(...head.map((i) => vertex(i)[2])) - Math.max(...wing.map((i) => vertex(i)[2]));
        expect(ahead).toBeGreaterThan(0.15);
        expect(ahead).toBeLessThan(0.35);
    });

    it('wears a bearded vulture\'s plumage: slate wings and tail, a rust breast, a cream head, the mask', () => {
        const chroma = (i) => {
            const [r, g, b] = colour(i);
            return (Math.max(r, g, b) - Math.min(r, g, b)) / Math.max(r, g, b, 1e-6);
        };
        // The wings and the tail are dark above and below; the underwing's coverts the darkest.
        for (const i of [...part('wing'), ...part('tail')]) {
            expect(luma(i), `vertex ${i}`).toBeLessThan(0.06);
            expect(chroma(i)).toBeLessThan(0.45);
        }
        const under = part('wing').filter((i) => normal(i)[1] < -0.8 && Math.abs(vertex(i)[0]) < 0.9);
        const front = under.filter((i) => model.feather[i * 4 + 1] < 0.42);
        const back = under.filter((i) => model.feather[i * 4 + 1] > 0.6);
        const mean = (list) => list.reduce((sum, i) => sum + luma(i), 0) / list.length;
        expect(front.length).toBeGreaterThan(8);
        expect(back.length).toBeGreaterThan(8);
        expect(mean(front)).toBeLessThan(mean(back) * 0.6);
        // The body from below: rust and orange (red over green over blue), far brighter than the wings.
        const belly = part('body').filter((i) => normal(i)[1] < -0.5 && vertex(i)[2] > -0.25);
        expect(belly.length).toBeGreaterThan(8);
        for (const i of belly) {
            const [r, g, b] = colour(i);
            expect(r).toBeGreaterThan(g * 1.6);
            expect(g).toBeGreaterThan(b * 1.8);
        }
        expect(mean(belly)).toBeGreaterThan(mean(part('wing')) * 4);
        // From above the back is slate like the wings.
        const back2 = part('body').filter((i) => normal(i)[1] > 0.8 && vertex(i)[2] < 0.2);
        back2.forEach((i) => expect(luma(i)).toBeLessThan(0.06));
        // The head is cream, with the black mask on its sides.
        const head = part('head');
        expect(Math.max(...head.map(luma))).toBeGreaterThan(0.5);
        expect(head.filter((i) => luma(i) < 0.02).length).toBeGreaterThanOrEqual(2);
        // Thin feathers let the sun through; the body does not.
        part('body').forEach((i) => expect(model.colours[i * 4 + 3]).toBe(0));
        expect(Math.max(...part('wing').map((i) => model.colours[i * 4 + 3]))).toBe(1);
        // Where a feather lies: numbered across the wing and the tail, 0..1 along it.
        for (const i of indices) {
            expect(model.feather[i * 4]).toBeGreaterThanOrEqual(0);
            expect(model.feather[i * 4]).toBeLessThan(40);
            if (model.parts[i] !== WING && model.parts[i] !== TAIL) expect(model.feather[i * 4 + 2]).toBe(0);
        }
    });

    it('carries shares in 0..1: none on the body, both hinges at the wingtips, the tail\'s own', () => {
        for (const i of indices) {
            const [arm, hand, tail, shade] = rig(i);
            for (const value of [arm, hand, tail, shade]) {
                expect(value).toBeGreaterThanOrEqual(0);
                expect(value).toBeLessThanOrEqual(1);
            }
            expect(shade).toBeGreaterThan(0.8);
            if (model.parts[i] !== WING) {
                expect(arm).toBe(0);
                expect(hand).toBe(0);
            } else expect(tail).toBe(0);
            if (model.parts[i] !== TAIL) expect(tail).toBe(0);
            // The hand's turn is taken only by what the arm's turn has wholly taken.
            if (hand > 0.02) expect(arm).toBeGreaterThan(0.98);
        }
        const tips = part('wing').filter((i) => Math.abs(vertex(i)[0]) > 1.25);
        tips.forEach((i) => expect(rig(i).slice(0, 2)).toEqual([1, 1]));
        const tail = part('tail');
        expect(Math.max(...tail.map((i) => rig(i)[2]))).toBe(1);
        expect(Math.min(...tail.map((i) => rig(i)[2]))).toBe(0);
        // The hinges lie where the script says: the shoulder at the body's side, the wrist at mid-wing.
        expect(M.shoulder[0]).toBeGreaterThan(0.05);
        expect(M.shoulder[0]).toBeLessThan(0.2);
        expect(M.wrist[0]).toBeGreaterThan(0.45);
        expect(M.wrist[0]).toBeLessThan(0.75);
        expect(M.fanGain).toBeGreaterThan(0.2);
    });

    it('folds as the script\'s own twin of the vertex stage does', () => {
        expect(M.checks.length).toBeGreaterThanOrEqual(12);
        const moved = new Set();
        for (const check of M.checks) {
            const posed = poseVulture(vertex(check.vertex), rig(check.vertex), check.arm, check.hand, check.fan, check.twist);
            posed.forEach((value, k) => expect(value, `vertex ${check.vertex} axis ${k}`).toBeCloseTo(check.at[k], 4));
            if (Math.hypot(...posed.map((value, k) => value - vertex(check.vertex)[k])) > 0.02) moved.add(model.parts[check.vertex]);
        }
        // The checks try a wing and the tail (a twin that ignored either would pass no other way).
        expect(moved.has(WING)).toBe(true);
        expect(moved.has(TAIL)).toBe(true);
        // At rest the model is as stored; the body and the head never move.
        for (const i of indices) {
            const rest = poseVulture(vertex(i), rig(i), 0, 0, 0, 0);
            const flown = poseVulture(vertex(i), rig(i), 0.46, -0.3, 1, 0.45);
            vertex(i).forEach((value, k) => {
                expect(rest[k]).toBeCloseTo(value, 9);
                if (model.parts[i] !== WING && model.parts[i] !== TAIL) expect(flown[k]).toBeCloseTo(value, 9);
            });
        }
        // A raised arm lifts the wingtip, a lowered hand drops it; a fan widens the tail, a twist tilts it.
        const tip = part('wing').reduce((best, i) => (vertex(i)[0] > vertex(best)[0] ? i : best));
        expect(poseVulture(vertex(tip), rig(tip), 0.4, 0)[1]).toBeGreaterThan(vertex(tip)[1] + 0.3);
        expect(poseVulture(vertex(tip), rig(tip), 0, -0.3)[1]).toBeLessThan(vertex(tip)[1] - 0.1);
        const edge = part('tail').reduce((best, i) => (vertex(i)[0] > vertex(best)[0] ? i : best));
        expect(poseVulture(vertex(edge), rig(edge), 0, 0, 1, 0)[0]).toBeGreaterThan(vertex(edge)[0] * 1.2);
        expect(poseVulture(vertex(edge), rig(edge), 0, 0, -1, 0)[0]).toBeLessThan(vertex(edge)[0] * 0.8);
        expect(Math.abs(poseVulture(vertex(edge), rig(edge), 0, 0, 0, 0.4)[1] - vertex(edge)[1])).toBeGreaterThan(0.05);
    });

    it('does not tear the skin anywhere in a flap, the soaring flex or the tail\'s steering', () => {
        const F = VULTURE_FLIGHT;
        /** The most any edge of the mesh stretches or shrinks in a pose (a tear is a long one). */
        const strain = (arm, hand, fan, twist) => {
            let worst = 1;
            for (let t = 0; t < model.triangleCount; t += 1) {
                const tri = [0, 1, 2].map((k) => model.index[t * 3 + k]);
                for (let k = 0; k < 3; k += 1) {
                    const a = tri[k];
                    const b = tri[(k + 1) % 3];
                    const rest = Math.hypot(...vertex(a).map((value, axis) => value - vertex(b)[axis]));
                    if (rest > 0.02) {
                        const pa = poseVulture(vertex(a), rig(a), arm, hand, fan, twist);
                        const pb = poseVulture(vertex(b), rig(b), arm, hand, fan, twist);
                        const ratio = Math.hypot(pa[0] - pb[0], pa[1] - pb[1], pa[2] - pb[2]) / rest;
                        worst = Math.max(worst, ratio, 1 / ratio);
                    }
                }
            }
            return worst;
        };
        // The wings through a whole slow flap, and the soaring flex at its ends.
        const flex = F.flex[0] + F.flex[2];
        const poses = [[F.arm + F.lift[0], F.hand + flex], [F.arm - F.lift[0], F.hand - flex]];
        for (let k = 0; k < 16; k += 1) {
            const theta = (k / 16) * Math.PI * 2;
            poses.push([F.arm + F.stroke[0] * Math.sin(theta), F.hand + F.stroke[1] * Math.sin(theta - F.stroke[2])]);
        }
        for (const [arm, hand] of poses) expect(strain(arm, hand, 0, 0)).toBeLessThan(1.5);
        // The tail: a full fan widens it by its gain and no more; a twist only shears it a little.
        expect(strain(F.arm, F.hand, 1, 0)).toBeLessThan(1 + M.fanGain + 0.01);
        expect(strain(F.arm, F.hand, -1, 0)).toBeLessThan(1 / (1 - M.fanGain) + 0.01);
        expect(strain(F.arm, F.hand, 0, 0.6)).toBeLessThan(1.12);
        // The soaring pose: the arm a touch raised, the hand lowered (wings a little bowed).
        expect(F.arm).toBeGreaterThan(0);
        expect(F.hand).toBeLessThan(0);
        expect(M.poses.soar[0]).toBeCloseTo(F.arm, 6);
        expect(M.poses.soar[1]).toBeCloseTo(F.hand, 6);
    });
});
