"""Neon District's shop people: a cast of cyberpunk characters baked into a relightable sprite sheet.

Run headless (nothing in an open Blender session is touched):

    blender --background --factory-startup --python scripts/blender/neon_district_people.py -- \
        [--textures public/textures/neon-district] [--js src/themes/neon-district/neon-district-people-atlas.js] \
        [--scratch <dir>] [--preview <dir>] [--only walkA,work]

Each clip (neon_people/clips.py) poses one character (neon_people/body.py: a body of ellipsoids
and round cones on a small rig, garments cut from it, hair, head gear, chrome limbs, glowing trims)
frame by frame, meshes every frame by surface nets and renders it from three or five views as data:
the view-space normal and occlusion in one sheet, the class weights (skin, hair, top, bottom,
chrome, glow; gear is the rest) in the other. The shop shader turns each person to face the
camera, picks the view and frame, colours the classes per person and lights them with the room.
No external assets are fetched: every body, garment and pose is generated here.

`--only` bakes a subset into the scratch folder (never the shipped files). `--preview` writes a lit
contact sheet of every clip's first frame.
"""

import argparse
import json
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import numpy as np  # noqa: E402

from neon_people import bake, clips, rig  # noqa: E402

COLUMNS = 32
SHEET_FILE = "people.webp"
MASK_FILE = "people-masks.webp"
GENERATOR = "Serenity Blocks - Neon District people (Blender authoring)"
TAG = "[neon-people]"


def _args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    parser = argparse.ArgumentParser()
    parser.add_argument("--textures", default=str(HERE.parent.parent / "public" / "textures" / "neon-district"))
    parser.add_argument("--js", default=str(HERE.parent.parent / "src" / "themes" / "neon-district"
                                            / "neon-district-people-atlas.js"))
    parser.add_argument("--scratch", default=None)
    parser.add_argument("--preview", default=None)
    parser.add_argument("--only", default=None)
    return parser.parse_args(argv)


def bake_all(names, scratch, log=print):
    stage = bake.Stage()
    stacks = {}
    try:
        for name in names:
            clip = clips.CLIPS[name]
            t0 = time.time()
            meshes = [bake.mesh_person(rig.pose(clip["build"], clip["pose"](ph)), clip["outfit"])
                      for ph in clips.phases(clip)]
            t1 = time.time()
            stacks[name] = bake.render_clip(stage, meshes, clips.VIEW_SETS[clip["views"]], scratch, name)
            log("%s %s: %d frames x %d views, meshed in %.0f s, rendered in %.0f s"
                % (TAG, name, clip["frames"], len(clips.VIEW_SETS[clip["views"]]), t1 - t0, time.time() - t1))
    finally:
        stage.dispose()
    return stacks


def pack(names, stacks):
    """Lay every clip's cells out row-major, view-major within a clip."""
    pw, ph = bake.CELL_PIXELS
    total = sum(clips.CLIPS[n]["frames"] * len(clips.VIEW_SETS[clips.CLIPS[n]["views"]]) for n in names)
    rows = -(-total // COLUMNS)
    rows += rows % 2  # the half-size masks stay whole
    atlas = np.zeros((rows * ph, COLUMNS * pw, stacks[names[0]].shape[2]), dtype=np.float32)
    table = {}
    cursor = 0
    for name in names:
        clip = clips.CLIPS[name]
        views = clips.VIEW_SETS[clip["views"]]
        stack = stacks[name]
        table[name] = cursor
        for v in range(len(views)):
            for f in range(clip["frames"]):
                cell = stack[v * ph:(v + 1) * ph, f * pw:(f + 1) * pw]
                index = cursor + v * clip["frames"] + f
                r, c = divmod(index, COLUMNS)
                atlas[r * ph:(r + 1) * ph, c * pw:(c + 1) * pw] = cell
        cursor += len(views) * clip["frames"]
    return atlas, table, rows, cursor


def write_js(path, names, table, rows, cells):
    views = {key: dict(start=v[0], step=v[1] - v[0], count=len(v)) for key, v in clips.VIEW_SETS.items()}
    lines = [
        "/**",
        " * Neon District — the shop people's sprite sheet (generated by scripts/blender/neon_district_people.py;",
        " * do not edit by hand).",
        " *",
        " * Cells are 1 m wide and 2 m tall, a person standing on the cell's bottom edge, centred. A clip's",
        " * cells run view-major: base + view * frames + frame, row-major in a sheet `columns` wide.",
        " * Views are degrees round the person from the face (mirrored for the other side): a clip is",
        " * drawn at `start + k * step` for k < count. `timing`: distance (a loop per `metres` walked),",
        " * loop (a loop per `seconds`) or level (frames along a 0..1 value, the breath).",
        " *",
        " * sheet  RGBA = normal x, normal y (view space, 0.5 + 0.5 n), coverage, 0.5 + 0.5 occlusion",
        " * masks  half size, two halves side by side: left RGBA = skin, hair, top, 1 - 0.5 bottom;",
        " *        right RGBA = chrome, glow, 0, 1. Gear (shoes, masks, bags) is what the weights leave.",
        " */",
        "export const PEOPLE_SHEET = Object.freeze({",
        "    url: './textures/neon-district/%s'," % SHEET_FILE,
        "    maskUrl: './textures/neon-district/%s'," % MASK_FILE,
        "    columns: %d," % COLUMNS,
        "    rows: %d," % rows,
        "    cells: %d," % cells,
        "    cellMetres: Object.freeze([%g, %g])," % bake.CELL_METRES,
        "    cellPixels: Object.freeze([%d, %d])," % bake.CELL_PIXELS,
        "});",
        "",
        "export const PEOPLE_VIEWS = Object.freeze({",
    ]
    for key, v in views.items():
        lines.append("    %s: Object.freeze({ start: %g, step: %g, count: %d })," % (key, v["start"], v["step"], v["count"]))
    lines += ["});", "", "export const PEOPLE_CLIPS = Object.freeze({"]
    for name in names:
        clip = clips.CLIPS[name]
        extra = ""
        if clip["timing"] == "distance":
            extra = ", metres: %g, seconds: %g" % (clip["metres"], clip["seconds"])
        elif clip["timing"] == "loop":
            extra = ", seconds: %g" % clip["seconds"]
        props = ["base: %d" % table[name], "frames: %d" % clip["frames"], "views: '%s'" % clip["views"],
                 "timing: '%s'" % clip["timing"]] + [e.strip() for e in extra.split(",") if e.strip()]
        lines.append("    %s: Object.freeze({" % name)
        lines += ["        %s," % prop for prop in props]
        lines.append("    }),")
    lines += ["});", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8", newline="\n")


def preview_sheet(path):
    stage = bake.Stage()
    try:
        rows = [[], []]
        for i, name in enumerate(clips.CLIPS):
            clip = clips.CLIPS[name]
            mesh = bake.mesh_person(rig.pose(clip["build"], clip["pose"](clips.phases(clip)[0])), clip["outfit"])
            yaw = {"side": 60.0, "front": 25.0, "back": 150.0}[clip["views"]]
            rows[i * 2 // len(clips.CLIPS)].append((mesh, clip["build"], yaw))
        bake.contact(stage, rows, path, pixels_per_metre=150, samples=32)
    finally:
        stage.dispose()


def main():
    args = _args()
    started = time.time()
    names = list(clips.CLIPS) if not args.only else [n.strip() for n in args.only.split(",")]
    scratch = Path(args.scratch or tempfile.mkdtemp(prefix="neon-people-"))
    scratch.mkdir(parents=True, exist_ok=True)
    stacks = bake_all(names, scratch)
    atlas, table, rows, cells = pack(names, stacks)
    sheet, masks = bake.encode(atlas)
    out = Path(args.textures) if not args.only else scratch
    out.mkdir(parents=True, exist_ok=True)
    bake.save_image(out / SHEET_FILE, sheet)
    bake.save_image(out / MASK_FILE, masks)
    js = Path(args.js) if not args.only else scratch / "neon-district-people-atlas.js"
    write_js(js, names, table, rows, cells)
    print("%s wrote %s, %s (%d cells, %d x %d) and %s in %.0f s" % (
        TAG, out / SHEET_FILE, out / MASK_FILE, cells, sheet.shape[1], sheet.shape[0], js, time.time() - started))
    if args.preview:
        Path(args.preview).mkdir(parents=True, exist_ok=True)
        preview_sheet(Path(args.preview) / "people-cast.png")
    record = dict(generator=GENERATOR, clips={n: table[n] for n in names}, cells=cells, rows=rows)
    (scratch / "people-bake.json").write_text(json.dumps(record, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
