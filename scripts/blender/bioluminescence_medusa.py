"""Model and bake the grotto medusa. Run in Blender with -- <output-model.js>."""

import base64
import math
import struct
import sys
from pathlib import Path

import bpy


def bake(destination):
    vertices, faces, pigments = [], [], []

    def strip(rows, columns, sample):
        start = len(vertices)
        for j in range(rows):
            for i in range(columns):
                point, pigment = sample(i / (columns - 1), j / (rows - 1))
                vertices.append(point)
                pigments.append(pigment)
                if j and i:
                    k = start + j * columns + i
                    faces.append((k - columns - 1, k - columns, k, k - 1))

    sin, cos, pi, tau = math.sin, math.cos, math.pi, math.tau

    def bell(u, t):
        a = tau * u
        arc = .012 + t * 1.80
        pleat = cos(12 * a) * .5 + .5
        r = sin(arc) * (.94 + .055 * pleat * t + .025 * sin(3 * a + .6))
        z = .87 * cos(arc) + .16 - .092 * t**5 * pleat
        return (r * cos(a), r * sin(a), z), (0, u, t)

    strip(12, 49, bell)

    # The four folded gastric pouches sit under the bell as an open rosette.
    for lobe in range(4):
        def pouch(u, t):
            a = lobe * pi / 2 + .4
            b = tau * t
            r = .24 + .17 * cos(b)
            along = .115 * sin(b)
            thick = (u - .5) * .085
            return ((r + thick) * cos(a) - along * sin(a),
                    (r + thick) * sin(a) + along * cos(a),
                    .34 + .105 * cos(b) + .05 * sin(u * pi)), (1, u, t)
        strip(13, 3, pouch)

    # Four ruffled oral arms twist independently and taper along the oral axis.
    for arm in range(4):
        def oral(u, t):
            a = arm * pi / 2 + .52 + t * 3.4
            r = .10 + .18 * sin(t * pi) + .085 * t
            wave = sin(t * 31 + arm * 1.31)
            hem = (u - .5) * (.28 + .11 * wave) * (1 - t)**.48
            z = .17 - t * (1.65 + .17 * arm) + .09 * wave * abs(2 * u - 1) * (1 - t)
            return (r * cos(a) - hem * sin(a), r * sin(a) + hem * cos(a), z), (2, u, t)
        strip(21, 4, oral)

    # Fine marginal tentacles trace the perimeter. Each tube has its own slack and length.
    for filament in range(12):
        def silk(u, t):
            a = tau * filament / 12
            reach = 2.25 + .85 * sin(a * 5 + .8)
            r = .89 + .11 * sin(t * 6.1 + a) * t - .22 * t
            twist = a + .31 * sin(4.6 * t + a * 2) * t
            width = .024 * (1 - .90 * t)
            return (r * cos(twist) + width * cos(u * tau),
                    r * sin(twist) + width * sin(u * tau),
                    -.055 - t * reach), (3, u, t)
        strip(12, 4, silk)

    scene = bpy.data.scenes.new('Bioluminescence medusa study')
    mesh = bpy.data.meshes.new('Scalloped bell, gastric rosette and oral arms')
    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    obj = bpy.data.objects.new('Grotto medusa', mesh)
    scene.collection.objects.link(obj)
    anatomy = mesh.attributes.new('anatomy', 'FLOAT_VECTOR', 'POINT')
    for item, pigment in zip(anatomy.data, pigments):
        item.vector = pigment
    mesh.calc_loop_triangles()

    # Coordinates are exported in the game's Y-up space. Twelve bytes per vertex.
    packed = bytearray()
    for vert, pigment in zip(mesh.vertices, pigments):
        x, y, z = vert.co
        nx, ny, nz = vert.normal
        packed += struct.pack('<hhhbbbBBB', *(round(v * 4096) for v in (x, z, -y)),
                              *(round(v * 127) for v in (nx, nz, -ny)),
                              pigment[0], round(255 * pigment[1]), round(255 * pigment[2]))
    triangles = b''.join(struct.pack('<HHH', *tri.vertices) for tri in mesh.loop_triangles)
    encode = lambda data: base64.b64encode(data).decode('ascii')
    Path(destination).write_text(
        '// Generated by scripts/blender/bioluminescence_medusa.py.\n'
        '/* eslint-disable max-len -- Packed binary mesh data. */\n'
        f"export const MEDUSA_VERTICES = '{encode(packed)}';\n"
        f"export const MEDUSA_INDICES = '{encode(triangles)}';\n", encoding='utf-8', newline='\n')
    return {'vertices': len(vertices), 'triangles': len(mesh.loop_triangles)}


if __name__ == '__main__':
    bake(sys.argv[sys.argv.index('--') + 1])
