function sharedFlag(name, category, description, scope, source, notes = '') {
    const declaration = FLAG_REGISTRY.find((flag) => flag.name === name);
    return {
        name,
        category,
        scope,
        description,
        values: '1 = on; 0 = off',
        defaultValue: declaration.default ? 'On (1)' : 'Off (0)',
        example: `${name}=${declaration.default ? '0' : '1'}`,
        notes: `${notes ? `${notes} ` : ''}URL values override the saved serenity.${name} `
            + 'localStorage value. Removing the URL parameter restores that saved value, if one exists.',
        sources: [source, 'src/core/flags.js'],
    };
}

function parameter(name, category, scope, description, values, defaultValue, example, source, notes = '') {
    return {
        name, category, scope, description, values, defaultValue, example, notes, sources: [source],
    };
}

