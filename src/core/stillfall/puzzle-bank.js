/**
 * The Stillfall pyramid: a hundred and thirty-eight puzzles in twelve tiers. First light
 * teaches with one piece each; Undertow and Deep fault deal two; Rift, Bedrock and Epicentre
 * deal three, and from Bedrock on exactly one first landing leads anywhere. Then each tier
 * adds something: Aftershock the seal (a body to clear away entirely), Cross fault two goals
 * at once, Mantle a fourth piece, and Core four pieces with two goals and the deepest
 * cascades. From the core the climb goes up: Uplift deals five pieces against towers of ten
 * to thirteen rows (the tiers before stand nine at most), built on and then brought down, and
 * Pinnacle five pieces against towers of up to fourteen rows with two goals at once. A tier
 * opens once three puzzles below it are solved, and at most two First light puzzles go
 * without a lantern, so a player always meets the lanterns before the deep fault assumes them.
 *
 * Authoring convention: lowercase letters are lanterns, bodies hanging in the air. They
 * follow the same rule as every body (after any clear, a body with nothing under it
 * falls); the case only tells an author which ones hang.
 *
 * Every puzzle has a straight-drop solution (rotate and move at the top, then drop): no
 * puzzle depends on a tuck or a kick. From two pieces up the last piece is needed (nothing
 * solves before it lands) and every piece matters (the puzzle is unsolvable without its
 * leading pieces). `solution` is one such line of play, for the hint; the certifier
 * (tests/unit/stillfall-puzzles*.test.js) proves all of this on every run.
 *
 * Structures from tier 2 on came from an offline search over random structures under those
 * rules (scripts/stillfall-search.mjs), kept when few openings win and the greedy opening
 * loses, then named and ordered by hand.
 */

